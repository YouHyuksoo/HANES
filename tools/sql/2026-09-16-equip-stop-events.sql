-- 설비정지 / 관리자호출 1단계 스키마
-- 대상: JSHANES
-- 설명:
--   EQUIP_STOP_EVENTS  설비정지 이벤트(정지 등록 → 사유 확정 → 해제 → 유실시간 확정)
--   EQUIP_CALL_EVENTS  관리자호출 이력(호출 → 응대)
--   COM_CODES          EQUIP_STOP_REASON / EQUIP_CALL_TYPE 코드 seed
-- 시각은 모두 서버 SYSTIMESTAMP 기준이다. 클라이언트 시계를 신뢰하지 않는다.
-- --execute-file 은 / 한 줄로 블록을 나눈다.

BEGIN
  EXECUTE IMMEDIATE q'~CREATE TABLE EQUIP_STOP_EVENTS (
    STOP_ID          NUMBER          NOT NULL,
    COMPANY          VARCHAR2(50)    NOT NULL,
    PLANT_CD         VARCHAR2(50)    NOT NULL,
    EQUIP_CODE       VARCHAR2(50)    NOT NULL,
    JOB_ORDER_NO     VARCHAR2(50),
    STOP_REASON      VARCHAR2(50),
    STOP_REMARK      VARCHAR2(500),
    STATUS           VARCHAR2(20)    DEFAULT 'OPEN' NOT NULL,
    STARTED_AT       TIMESTAMP       DEFAULT CURRENT_TIMESTAMP NOT NULL,
    STARTED_BY       VARCHAR2(50),
    RELEASED_AT      TIMESTAMP,
    RELEASED_BY      VARCHAR2(50),
    RELEASE_REMARK   VARCHAR2(500),
    LOSS_SECONDS     NUMBER,
    PREV_EQUIP_STATUS VARCHAR2(20),
    CREATED_BY       VARCHAR2(50),
    UPDATED_BY       VARCHAR2(50),
    CREATED_AT       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EQUIP_STOP_EVENTS PRIMARY KEY (STOP_ID),
    CONSTRAINT CK_EQUIP_STOP_STATUS CHECK (STATUS IN ('OPEN','CLOSED'))
  )~';
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'~COMMENT ON TABLE EQUIP_STOP_EVENTS IS '설비정지 이벤트. 키오스크에서 등록하고 해제 시 유실시간(LOSS_SECONDS)을 서버가 확정한다'~';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'~COMMENT ON COLUMN EQUIP_STOP_EVENTS.STOP_REASON IS '정지사유. COM_CODES(EQUIP_STOP_REASON). NULL=사유미정(해제 전 확정 필요)'~';
  EXECUTE IMMEDIATE q'~COMMENT ON COLUMN EQUIP_STOP_EVENTS.STATUS IS 'OPEN=정지중, CLOSED=해제완료'~';
  EXECUTE IMMEDIATE q'~COMMENT ON COLUMN EQUIP_STOP_EVENTS.LOSS_SECONDS IS '유실시간(초). 해제 시 RELEASED_AT-STARTED_AT 로 서버가 계산해 고정한다'~';
  EXECUTE IMMEDIATE q'~COMMENT ON COLUMN EQUIP_STOP_EVENTS.PREV_EQUIP_STATUS IS '정지 직전 EQUIP_MASTERS.STATUS. 해제 시 이 값으로 되돌린다'~';
EXCEPTION WHEN OTHERS THEN NULL;
END;
/

-- 설비당 진행중(OPEN) 정지는 1건만 허용한다. CLOSED 행은 NULL 이 되어 인덱스에 들어가지 않는다.
BEGIN
  EXECUTE IMMEDIATE q'~CREATE UNIQUE INDEX UX_EQUIP_STOP_OPEN ON EQUIP_STOP_EVENTS (
    CASE WHEN STATUS = 'OPEN' THEN COMPANY END,
    CASE WHEN STATUS = 'OPEN' THEN PLANT_CD END,
    CASE WHEN STATUS = 'OPEN' THEN EQUIP_CODE END
  )~';
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'~CREATE INDEX IX_EQUIP_STOP_EQUIP ON EQUIP_STOP_EVENTS (COMPANY, PLANT_CD, EQUIP_CODE, STARTED_AT)~';
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'~CREATE INDEX IX_EQUIP_STOP_ORDER ON EQUIP_STOP_EVENTS (COMPANY, PLANT_CD, JOB_ORDER_NO)~';
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
  EXECUTE IMMEDIATE q'~CREATE SEQUENCE SEQ_EQUIP_STOP_EVENTS START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE~';
EXCEPTION
  WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

