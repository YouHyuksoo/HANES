-- ── 공통코드 seed ─────────────────────────────────────────────
-- ATTR1 = 손실분류(PLANNED/SETUP/FAILURE/MANAGEMENT/SPEED/QUALITY) — 가동률 산출 도입 시 사용할 자리만 채워둔다.
-- ATTR2 = 통제가능여부(Y/N)
MERGE INTO COM_CODES t
USING (
  SELECT 'EQUIP_STOP_REASON' GROUP_CODE, 'FAILURE'   DETAIL_CODE, '설비고장'   CODE_NAME, 1 SORT_ORDER, 'FAILURE'    ATTR1, 'Y' ATTR2 FROM DUAL UNION ALL
  SELECT 'EQUIP_STOP_REASON', 'JAM',        '부품걸림',        2, 'FAILURE',    'Y' FROM DUAL UNION ALL
  SELECT 'EQUIP_STOP_REASON', 'MAT_SHORT',  '자재결품',        3, 'MANAGEMENT', 'Y' FROM DUAL UNION ALL
  SELECT 'EQUIP_STOP_REASON', 'MODEL_CHG',  '모델교체',        4, 'SETUP',      'Y' FROM DUAL UNION ALL
  SELECT 'EQUIP_STOP_REASON', 'SETUP',      '작업준비',        5, 'SETUP',      'Y' FROM DUAL UNION ALL
  SELECT 'EQUIP_STOP_REASON', 'QUALITY',    '품질이상',        6, 'QUALITY',    'Y' FROM DUAL UNION ALL
  SELECT 'EQUIP_STOP_REASON', 'NO_WORKER',  '작업자부재',      7, 'MANAGEMENT', 'Y' FROM DUAL UNION ALL
  SELECT 'EQUIP_STOP_REASON', 'POWER',      '정전',            8, 'FAILURE',    'N' FROM DUAL UNION ALL
  SELECT 'EQUIP_STOP_REASON', 'MAINT',      '예방정비',        9, 'PLANNED',    'Y' FROM DUAL UNION ALL
  SELECT 'EQUIP_STOP_REASON', 'ETC',        '기타',           99, 'MANAGEMENT', 'Y' FROM DUAL UNION ALL
  SELECT 'EQUIP_CALL_TYPE',   'EQUIP',      '설비이상',        1, NULL,         NULL FROM DUAL UNION ALL
  SELECT 'EQUIP_CALL_TYPE',   'QUALITY',    '품질문의',        2, NULL,         NULL FROM DUAL UNION ALL
  SELECT 'EQUIP_CALL_TYPE',   'MATERIAL',   '자재요청',        3, NULL,         NULL FROM DUAL UNION ALL
  SELECT 'EQUIP_CALL_TYPE',   'ETC',        '기타',           99, NULL,         NULL FROM DUAL
) s
ON (t.GROUP_CODE = s.GROUP_CODE AND t.DETAIL_CODE = s.DETAIL_CODE AND t.COMPANY = '40' AND t.PLANT_CD = '1000')
WHEN MATCHED THEN UPDATE SET
  t.CODE_NAME = s.CODE_NAME,
  t.SORT_ORDER = s.SORT_ORDER,
  t.ATTR1 = s.ATTR1,
  t.ATTR2 = s.ATTR2,
  t.USE_YN = 'Y',
  t.UPDATED_AT = SYSTIMESTAMP,
  t.UPDATED_BY = 'system'
WHEN NOT MATCHED THEN INSERT (
  GROUP_CODE, DETAIL_CODE, CODE_NAME, SORT_ORDER, USE_YN, ATTR1, ATTR2,
  COMPANY, PLANT_CD, CREATED_BY, UPDATED_BY, CREATED_AT, UPDATED_AT
) VALUES (
  s.GROUP_CODE, s.DETAIL_CODE, s.CODE_NAME, s.SORT_ORDER, 'Y', s.ATTR1, s.ATTR2,
  '40', '1000', 'system', 'system', SYSTIMESTAMP, SYSTIMESTAMP
)
/

