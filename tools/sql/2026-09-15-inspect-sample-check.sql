/
COMMENT ON COLUMN INSPECT_AIDS.REQUIRED_YN IS '검사 전 대조 필수 여부 (Y=필수, N=참고용)'
/
COMMENT ON COLUMN INSPECT_AIDS.SORT_ORDER IS '대조 모달 표시 순서'
/
