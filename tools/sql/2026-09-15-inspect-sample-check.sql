  INSPECT_TYPE VARCHAR2(30),
  REQUIRED_YN  VARCHAR2(1) DEFAULT 'Y' NOT NULL,
  SORT_ORDER   NUMBER(5)   DEFAULT 0   NOT NULL
)
/
