-- 작업지시 실적 = 오늘 실적 합계 (DONE 은 균등분할이라 계획과 정확히 일치)
UPDATE JOB_ORDERS jo
   SET (GOOD_QTY, DEFECT_QTY) = (
         SELECT NVL(SUM(GOOD_QTY), 0), NVL(SUM(DEFECT_QTY), 0)
           FROM PROD_RESULTS pr
          WHERE pr.ORDER_NO = jo.ORDER_NO AND pr.RESULT_NO LIKE 'PRSEED-T%'),
       END_TIME = CASE WHEN jo.STATUS = 'DONE' THEN TRUNC(SYSDATE) + 16 / 24 END
 WHERE jo.ORDER_NO LIKE 'WOSEED-%' AND jo.STATUS <> 'WAITING'
/

