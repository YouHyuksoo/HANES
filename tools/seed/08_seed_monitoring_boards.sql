INSERT INTO DEFECT_LOGS (OCCUR_TIME, SEQ, PROD_RESULT_ID, DEFECT_CODE, DEFECT_NAME, QTY, STATUS, COMPANY, PLANT_CD, CREATED_BY)
SELECT pr.CREATED_AT, 1, pr.RESULT_NO, dc.DEFECT_CODE, dc.DEFECT_NAME,
       CASE WHEN pr.DEFECT_QTY >= 4 THEN CEIL(pr.DEFECT_QTY / 2) ELSE pr.DEFECT_QTY END,
       'WAIT', '40', '1000', 'SEED'
  FROM PROD_RESULTS pr
  JOIN DEFECT_CODE_MASTERS dc
    ON dc.COMPANY = '40'
   AND dc.DEFECT_CODE = CASE MOD(TO_NUMBER(SUBSTR(pr.RESULT_NO, 9, 2)) * 3 + TO_NUMBER(SUBSTR(pr.RESULT_NO, -2)), 8)
                          WHEN 0 THEN 'APP' WHEN 1 THEN 'ASM' WHEN 2 THEN 'CRACK' WHEN 3 THEN 'DIM'
                          WHEN 4 THEN 'FUNC' WHEN 5 THEN 'WELD' WHEN 6 THEN 'WORK' ELSE 'MAT' END
 WHERE pr.RESULT_NO LIKE 'PRSEED-T%' AND pr.DEFECT_QTY > 0
/
INSERT INTO DEFECT_LOGS (OCCUR_TIME, SEQ, PROD_RESULT_ID, DEFECT_CODE, DEFECT_NAME, QTY, STATUS, COMPANY, PLANT_CD, CREATED_BY)
