       FLOOR(pr.DEFECT_QTY / 2), 'WAIT', '40', '1000', 'SEED'
  FROM PROD_RESULTS pr
  JOIN DEFECT_CODE_MASTERS dc
    ON dc.COMPANY = '40'
   AND dc.DEFECT_CODE = CASE MOD(TO_NUMBER(SUBSTR(pr.RESULT_NO, 9, 2)) * 3 + TO_NUMBER(SUBSTR(pr.RESULT_NO, -2)) + 3, 8)
                          WHEN 0 THEN 'APP' WHEN 1 THEN 'ASM' WHEN 2 THEN 'CRACK' WHEN 3 THEN 'DIM'
