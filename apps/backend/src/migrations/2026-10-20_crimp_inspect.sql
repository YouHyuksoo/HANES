-- 단자검사(INSP_TERMINAL_RESULT)를 절압물검사로 전환 (JSHANES 40/1000)
-- 1. INSPECT_RESULTS.ORDER_NO — 절압물검사는 FG 라벨·생산실적 이전(초물)에도 기록하므로 작업지시를 직접 건다
-- 2. INSPECT_TYPE.TERMINAL 명칭을 절압물로 변경
-- 3. 절압물 외관 판정 항목 공통코드 CRIMP_VISUAL_CHECK

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME = 'INSPECT_RESULTS' AND COLUMN_NAME = 'ORDER_NO';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE INSPECT_RESULTS ADD ORDER_NO VARCHAR2(50)';
  END IF;
  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'IX_INSPECT_RESULTS_ORDER';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_INSPECT_RESULTS_ORDER ON INSPECT_RESULTS (COMPANY, PLANT_CD, ORDER_NO, INSPECT_TYPE)';
  END IF;
END;
/

COMMENT ON COLUMN INSPECT_RESULTS.ORDER_NO IS '작업지시번호 - 작업지시 단위 검사(절압물검사 TERMINAL)에서 직접 기록'
/

MERGE INTO COM_CODES c
USING (
  SELECT 'INSPECT_TYPE' AS GROUP_CODE, 'TERMINAL' AS DETAIL_CODE, '절압물' AS CODE_NAME, '절단·압착 반제품(절압물)의 압착 규격·외관 검사' AS CODE_DESC, 7 AS SORT_ORDER FROM DUAL UNION ALL
  SELECT 'CRIMP_VISUAL_CHECK', 'SHAPE', '압착형상', '압착부 형상·벨마우스·심선 돌출 상태', 1 FROM DUAL UNION ALL
  SELECT 'CRIMP_VISUAL_CHECK', 'MIXUP', '이종', '단자·전선 품번 혼입 여부', 2 FROM DUAL UNION ALL
  SELECT 'CRIMP_VISUAL_CHECK', 'MISSING', '누락', '씰·부자재 누락 여부', 3 FROM DUAL UNION ALL
  SELECT 'CRIMP_VISUAL_CHECK', 'APPEARANCE', '외관불량', '단자 변형·피복 손상 등 외관 불량', 4 FROM DUAL
) s
ON (c.COMPANY = '40' AND c.PLANT_CD = '1000' AND c.GROUP_CODE = s.GROUP_CODE AND c.DETAIL_CODE = s.DETAIL_CODE)
WHEN MATCHED THEN UPDATE SET c.CODE_NAME = s.CODE_NAME, c.CODE_DESC = s.CODE_DESC, c.SORT_ORDER = s.SORT_ORDER, c.USE_YN = 'Y', c.UPDATED_BY = 'claude', c.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (GROUP_CODE, DETAIL_CODE, CODE_NAME, CODE_DESC, SORT_ORDER, USE_YN, COMPANY, PLANT_CD, CREATED_BY, UPDATED_BY, CREATED_AT, UPDATED_AT)
  VALUES (s.GROUP_CODE, s.DETAIL_CODE, s.CODE_NAME, s.CODE_DESC, s.SORT_ORDER, 'Y', '40', '1000', 'claude', 'claude', SYSTIMESTAMP, SYSTIMESTAMP)
/

COMMIT
