-- DDL로 INVALID 된 PL/SQL 재컴파일
BEGIN
  FOR o IN (SELECT OBJECT_NAME, OBJECT_TYPE FROM USER_OBJECTS WHERE STATUS = 'INVALID' AND OBJECT_TYPE IN ('PACKAGE','PACKAGE BODY','PROCEDURE','FUNCTION','TRIGGER','VIEW')) LOOP
    BEGIN
      IF o.OBJECT_TYPE = 'PACKAGE BODY' THEN
        EXECUTE IMMEDIATE 'ALTER PACKAGE ' || o.OBJECT_NAME || ' COMPILE BODY';
      ELSE
        EXECUTE IMMEDIATE 'ALTER ' || o.OBJECT_TYPE || ' ' || o.OBJECT_NAME || ' COMPILE';
      END IF;
    EXCEPTION WHEN OTHERS THEN NULL;
    END;
  END LOOP;
END;
