-- THN A50 템플릿을 RAW 품목에 적용 (ITEM_NAME 매핑). 기존 SEQ 1~n은 유지, THN 항목은 SEQ 100번대.
-- 대상: JSHANES 40/1000. MERGE 멱등.

MERGE INTO IQC_PART_SPECS t
USING (
  SELECT ITEM_CODE
  FROM ITEM_MASTERS
  WHERE COMPANY = '40' AND PLANT_CD = '1000' AND NVL(USE_YN,'Y') = 'Y' AND ITEM_TYPE = 'RAW_MATERIAL'
    AND ITEM_CODE NOT LIKE '%\_FAIL' ESCAPE '\'
    AND ITEM_CODE NOT LIKE '%\_PASS' ESCAPE '\'
    AND UPPER(TRIM(ITEM_NAME)) IN (
      'WIRE','LEAD WIRE','TUBE','TAPE','TML','EARTH TML','TERMINAL',
      'CRIMP RING','CRIMP SHILED','CRIMP SHIELD','HSG','HOUSING','SEAL','B/CABLE'
    )
) s
ON (t.COMPANY = '40' AND t.PLANT_CD = '1000' AND t.ITEM_CODE = s.ITEM_CODE)
WHEN MATCHED THEN UPDATE SET
  t.USE_YN = 'Y', t.UPDATED_BY = 'thn-a50-seed', t.UPDATED_AT = SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT (
  COMPANY, PLANT_CD, ITEM_CODE, SAMPLE_QTY, IS_DEST, USE_YN,
  CREATED_BY, UPDATED_BY, CREATED_AT, UPDATED_AT
) VALUES (
  '40', '1000', s.ITEM_CODE, 1, 'N', 'Y',
  'thn-a50-seed', 'thn-a50-seed', SYSTIMESTAMP, SYSTIMESTAMP
)
