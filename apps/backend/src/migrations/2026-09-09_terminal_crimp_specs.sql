-- 4) 메뉴 등록: QC_TERMINAL_CRIMP_SPEC (QUALITY, /master/terminal-crimp-spec, labelKey menu.master.terminalCrimpSpec)
--    DB QUALITY 카테고리 실측(2026-09-09): QC_IQC_PART_SPEC 행 없음, QC_IQC=10이 첫 항목 → menuConfig 순서(QC_IQC_PART_SPEC 다음)대로 5에 배치.
MERGE INTO MENU_CATEGORY_ITEMS t
USING (
  SELECT 'QC_TERMINAL_CRIMP_SPEC' AS MENU_CODE,
         'QUALITY'                AS CATEGORY_CODE,
         5                        AS SORT_ORDER,
         '40'                     AS COMPANY,
         '1000'                   AS PLANT_CD
  FROM dual
) s
ON (t.MENU_CODE = s.MENU_CODE AND t.COMPANY = s.COMPANY AND t.PLANT_CD = s.PLANT_CD)
WHEN NOT MATCHED THEN
  INSERT (MENU_CODE, CATEGORY_CODE, SORT_ORDER, COMPANY, PLANT_CD,
          CREATED_AT, CREATED_BY, UPDATED_AT, UPDATED_BY)
  VALUES (s.MENU_CODE, s.CATEGORY_CODE, s.SORT_ORDER, s.COMPANY, s.PLANT_CD,
          SYSTIMESTAMP, 'system', SYSTIMESTAMP, 'system')
/

MERGE INTO ROLE_MENU_PERMISSIONS t
USING (
  SELECT 'MANAGER'  AS ROLE_CODE, 'QC_TERMINAL_CRIMP_SPEC' AS MENU_CODE, '40' AS COMPANY, '1000' AS PLANT_CD FROM dual
  UNION ALL
  SELECT 'OPERATOR' AS ROLE_CODE, 'QC_TERMINAL_CRIMP_SPEC' AS MENU_CODE, '40' AS COMPANY, '1000' AS PLANT_CD FROM dual
