-- 1) 테이블 · 시퀀스 · UNIQUE
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'TERMINAL_CRIMP_SPECS';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE TERMINAL_CRIMP_SPECS (
      SPEC_ID              NUMBER(15,0)   NOT NULL,
      COMPANY              VARCHAR2(50)   NOT NULL,
      PLANT_CD             VARCHAR2(50)   NOT NULL,
      TERMINAL_ITEM_CODE   VARCHAR2(50)   NOT NULL,
      TERMINAL_TYPE        VARCHAR2(30),
      WIRE_SIZE            VARCHAR2(50)   NOT NULL,
      WIRE_ITEM_CODE       VARCHAR2(50),
      CRIMP_HEIGHT_LSL     NUMBER(10,3),
      CRIMP_HEIGHT_USL     NUMBER(10,3),
      CRIMP_WIDTH_LSL      NUMBER(10,3),
      CRIMP_WIDTH_USL      NUMBER(10,3),
      INS_CRIMP_HEIGHT_LSL NUMBER(10,3),
      INS_CRIMP_HEIGHT_USL NUMBER(10,3),
      PULL_FORCE_MIN       NUMBER(10,3),
      STRIP_LENGTH_MIN     NUMBER(10,3),
      STRIP_LENGTH_MAX     NUMBER(10,3),
      APPLICATOR_CODE      VARCHAR2(50),
      REMARK               VARCHAR2(500),
      USE_YN               CHAR(1)        DEFAULT ''Y'' NOT NULL,
      CREATED_BY           VARCHAR2(50),
      UPDATED_BY           VARCHAR2(50),
      CREATED_AT           TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT           TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_TERMINAL_CRIMP_SPECS PRIMARY KEY (SPEC_ID),
      CONSTRAINT UK_TERMINAL_CRIMP_SPECS UNIQUE (COMPANY, PLANT_CD, TERMINAL_ITEM_CODE, WIRE_SIZE),
      CONSTRAINT CK_TERMINAL_CRIMP_USE_YN CHECK (USE_YN IN (''Y'',''N''))
    )';
  END IF;

  SELECT COUNT(*) INTO n FROM USER_SEQUENCES WHERE SEQUENCE_NAME = 'SEQ_TERMINAL_CRIMP_SPEC';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE SEQUENCE SEQ_TERMINAL_CRIMP_SPEC START WITH 1 INCREMENT BY 1 MAXVALUE 999999999999999 NOCYCLE CACHE 20';
  END IF;

  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME = 'IX_TERMINAL_CRIMP_TERMINAL';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_TERMINAL_CRIMP_TERMINAL ON TERMINAL_CRIMP_SPECS (COMPANY, PLANT_CD, TERMINAL_ITEM_CODE)';
  END IF;
END;
/

