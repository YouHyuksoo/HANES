-- 작업지시 묶음 출고요청 — 품목 1줄(합계) 아래 작업지시별 요청/출고수량
-- 같은 공정 작업지시 여러 건을 출고요청 1건으로 묶는다. 이 테이블에 행이 있는 요청이 묶음 요청이다.
-- 1:1 요청(헤더 ORDER_NO)은 기존 그대로 이 테이블을 쓰지 않는다.
-- 불변식: 품목별 SUM(REQUEST_QTY)=MAT_ISSUE_REQUEST_ITEMS.REQUEST_QTY, SUM(ISSUED_QTY)=MAT_ISSUE_REQUEST_ITEMS.ISSUED_QTY
-- 대상: JSHANES. 멱등(존재 확인 후 생성).
-- 실행: python C:/Users/hsyou/.claude/skills/oracle-db/scripts/oracle_connector.py --site JSHANES --execute-file <this file>
-- 적용 후: ORACLE_SITE=JSHANES python tools/generate_db_schema_doc.py

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME = 'MAT_ISSUE_REQUEST_ITEM_ORDERS';
  IF n = 0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE MAT_ISSUE_REQUEST_ITEM_ORDERS (
      COMPANY         VARCHAR2(50)   NOT NULL,
      PLANT_CD        VARCHAR2(50)   NOT NULL,
      REQUEST_ID      VARCHAR2(50)   NOT NULL,
      ITEM_SEQ        NUMBER         NOT NULL,
      ORDER_NO        VARCHAR2(50)   NOT NULL,
      REQUEST_QTY     NUMBER(10,0)   NOT NULL,
      ISSUED_QTY      NUMBER(10,0)   DEFAULT 0 NOT NULL,
      BOM_REQ_QTY     NUMBER(12,3),
      PREV_ISSUE_QTY  NUMBER(12,3),
      CREATED_BY      VARCHAR2(50),
      UPDATED_BY      VARCHAR2(50),
      CREATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
      UPDATED_AT      TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT PK_MAT_ISSUE_REQ_ITEM_ORDERS PRIMARY KEY (COMPANY, PLANT_CD, REQUEST_ID, ITEM_SEQ, ORDER_NO),
      CONSTRAINT CK_MAT_ISSUE_REQ_ITEM_ORD_QTY CHECK (REQUEST_QTY >= 0 AND ISSUED_QTY >= 0)
    )';
    EXECUTE IMMEDIATE 'CREATE INDEX IX_MAT_ISSUE_REQ_ITEM_ORD_ORDER ON MAT_ISSUE_REQUEST_ITEM_ORDERS (COMPANY, PLANT_CD, ORDER_NO)';
    EXECUTE IMMEDIATE q'[COMMENT ON TABLE MAT_ISSUE_REQUEST_ITEM_ORDERS IS '묶음 출고요청 작업지시별 수량 — 품목(MAT_ISSUE_REQUEST_ITEMS) 1줄 아래 작업지시별 요청/출고수량. 행이 있는 요청이 묶음 요청']';
    EXECUTE IMMEDIATE q'[COMMENT ON COLUMN MAT_ISSUE_REQUEST_ITEM_ORDERS.REQUEST_ID IS '출고요청번호(MAT_ISSUE_REQUESTS.REQUEST_NO)']';
    EXECUTE IMMEDIATE q'[COMMENT ON COLUMN MAT_ISSUE_REQUEST_ITEM_ORDERS.ITEM_SEQ IS '요청 품목 순번(MAT_ISSUE_REQUEST_ITEMS.SEQ)']';
    EXECUTE IMMEDIATE q'[COMMENT ON COLUMN MAT_ISSUE_REQUEST_ITEM_ORDERS.ORDER_NO IS '묶인 작업지시번호(JOB_ORDERS.ORDER_NO, 품목지시)']';
    EXECUTE IMMEDIATE q'[COMMENT ON COLUMN MAT_ISSUE_REQUEST_ITEM_ORDERS.REQUEST_QTY IS '작업지시별 요청수량. 품목별 합계=MAT_ISSUE_REQUEST_ITEMS.REQUEST_QTY']';
    EXECUTE IMMEDIATE q'[COMMENT ON COLUMN MAT_ISSUE_REQUEST_ITEM_ORDERS.ISSUED_QTY IS '작업지시별 출고수량. 출고 시 작업지시 계획일 빠른 순으로 배분. 품목별 합계=MAT_ISSUE_REQUEST_ITEMS.ISSUED_QTY']';
    EXECUTE IMMEDIATE q'[COMMENT ON COLUMN MAT_ISSUE_REQUEST_ITEM_ORDERS.BOM_REQ_QTY IS '작업지시 BOM 소요량(요청 시점)']';
    EXECUTE IMMEDIATE q'[COMMENT ON COLUMN MAT_ISSUE_REQUEST_ITEM_ORDERS.PREV_ISSUE_QTY IS '작업지시 기출고량(요청 시점, MAT_ISSUES.ORDER_NO 기준)']';
  END IF;
END;
