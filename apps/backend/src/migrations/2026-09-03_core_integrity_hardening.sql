  IF v_count = 0 THEN
    EXECUTE IMMEDIATE 'ALTER TABLE PRODUCT_STOCKS ADD CONSTRAINT CK_PRODUCT_STOCKS_QTY_INVARIANT CHECK (QTY >= 0 AND RESERVED_QTY >= 0 AND AVAILABLE_QTY >= 0 AND AVAILABLE_QTY = QTY - RESERVED_QTY)';
