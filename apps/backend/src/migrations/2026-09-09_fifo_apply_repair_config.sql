-- 수리 부품 소비(issueType REPAIR) FIFO 적용 여부 옵션 (T-CUSTOMER-AUDIT-GAPS 후속, 사용자 결정 2026-09-09)
-- 기본 N: 수리 소비는 FIFO 검사를 건너뛴다(유효기간 만료 차단은 유지). 멱등 MERGE, COMPANY='40', PLANT_CD='1000'.
-- SORT_ORDER 16 = MATERIAL 그룹 EXPIRED_ISSUE_BLOCK(15) 다음.

MERGE INTO SYS_CONFIGS t
USING (
  SELECT 'MATERIAL' AS CONFIG_GROUP, 'FIFO_APPLY_REPAIR' AS CONFIG_KEY, 'N' AS CONFIG_VALUE, 'BOOLEAN' AS CONFIG_TYPE,
         '수리 부품 소비 선입선출 적용' AS LABEL,
         '수리 작업의 부품 소비 출고(REPAIR)에도 선입선출(FIFO_ACTION) 검사를 적용할지 (Y=적용, N=수리 소비는 FIFO 제외). 유효기간 만료 LOT 차단은 이 설정과 무관하게 적용됩니다.' AS DESCRIPTION,
         NULL AS OPTIONS, 16 AS SORT_ORDER, '40' AS COMPANY, '1000' AS PLANT_CD
  FROM dual
) s
ON (t.CONFIG_KEY = s.CONFIG_KEY AND t.COMPANY = s.COMPANY AND t.PLANT_CD = s.PLANT_CD)
WHEN NOT MATCHED THEN
  INSERT (CONFIG_GROUP, CONFIG_KEY, CONFIG_VALUE, CONFIG_TYPE, LABEL, DESCRIPTION, OPTIONS, SORT_ORDER, IS_ACTIVE, COMPANY, PLANT_CD, CREATED_BY, UPDATED_BY, CREATED_AT, UPDATED_AT)
  VALUES (s.CONFIG_GROUP, s.CONFIG_KEY, s.CONFIG_VALUE, s.CONFIG_TYPE, s.LABEL, s.DESCRIPTION, s.OPTIONS, s.SORT_ORDER, 'Y', s.COMPANY, s.PLANT_CD, 'system', 'system', SYSTIMESTAMP, SYSTIMESTAMP)
/
