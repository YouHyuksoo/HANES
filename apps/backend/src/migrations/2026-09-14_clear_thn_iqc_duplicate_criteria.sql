       UPDATED_BY = 'thn-a50-seed',
       UPDATED_AT = SYSTIMESTAMP
 WHERE COMPANY = '40' AND PLANT_CD = '1000'
   AND TEMPLATE_ID LIKE 'THN-A50%'
   AND JUDGE_CRITERIA IS NOT NULL
